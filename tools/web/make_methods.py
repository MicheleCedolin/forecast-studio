"""Writes web/methods.js: the method list of the web edition, with names and one-line summaries taken from the desktop
application's model descriptions (src/tsfstudio/app/models_info.py), so the two editions describe a method in the same words.

    python tools/web/make_methods.py
"""
from __future__ import annotations

import json
from pathlib import Path

from tsfstudio.app.models_info import MODELS

# Families in display order. `cost` marks methods that take seconds per series in the browser (measured on NN5 Weekly).
FAMILIES = [
    ("Benchmarks", ["naive", "snaive", "drift", "naive2", "historic_average", "window_average", "seasonal_window_average", "zero_model"]),
    ("Exponential smoothing", ["ses", "holt_ets", "holt_winters", "ets", "seasonal_es", "auto_ces"]),
    ("Theta", ["theta", "dotm", "auto_theta"]),
    ("ARIMA", ["arima", "dhr_arima"]),
    ("Decomposition and several seasonal periods", ["stl_ets", "stl_arima", "mstl", "tbats", "auto_mfles"]),
    ("Combinations", ["comb_shd", "scum", "bagged_ets", "thief", "mapa"]),
    ("Intermittent demand", ["croston_classic", "croston_sba", "croston_optimized", "tsb", "adida", "imapa"]),
    ("Global (one model for all series)", ["pooled_regression"]),
]
SLOW = {"tbats", "bagged_ets", "thief", "mapa", "arima", "scum", "comb_shd"}

out = []
for family, ids in FAMILIES:
    for mid in ids:
        m = MODELS[mid]
        out.append({"id": mid, "name": m["name"], "family": family, "task": m["task"], "slow": mid in SLOW, "summary": m["summary"]})

text = ("// Generated by tools/web/make_methods.py from src/tsfstudio/app/models_info.py. Do not edit by hand.\n"
        "export const METHODS = " + json.dumps(out, indent=1, ensure_ascii=False) + ";\n")
dest = Path(__file__).resolve().parents[2] / "web" / "methods.js"
dest.write_text(text, encoding="utf-8", newline="\n")
print(f"{dest}: {len(out)} methods")
